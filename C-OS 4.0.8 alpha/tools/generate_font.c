#include <stdio.h>
#include <stdint.h>

/* Simple 12x16 font generator for C-OS
 * Generates font data compatible with the rendering logic:
 * - bit_idx = col (extracts bits from left to right)
 * - glyph->rows[row] (rows are not reversed)
 */

typedef struct {
    uint16_t codepoint;
    uint32_t rows[16];
} vga_font24_glyph_t;

/* Convert character bitmap to uint32_t values */
void char_to_bits(const char* char_data[16], uint32_t* rows) {
    for (int row = 0; row < 16; row++) {
        uint32_t bits = 0;
        for (int col = 0; col < 12; col++) {
            if (char_data[row][col] == '#') {
                bits |= (1u << col);  // bit 0 is leftmost, bit 11 is rightmost
            }
        }
        rows[row] = bits;
    }
}

/* Generate a simple 12x16 bitmap for any ASCII character */
void generate_simple_char(uint16_t codepoint, const char* rows[16]) {
    static char buffer[16][13];  // 16 rows, 12 chars + null terminator
    
    if (codepoint == 0x20) {  // Space
        for (int row = 0; row < 16; row++) {
            for (int col = 0; col < 12; col++) {
                buffer[row][col] = '.';
            }
            buffer[row][12] = '\0';
            rows[row] = buffer[row];
        }
        return;
    }
    
    /* For other characters, create a simple pattern based on the codepoint */
    for (int row = 0; row < 16; row++) {
        for (int col = 0; col < 12; col++) {
            if ((codepoint + row + col) % 7 == 0) {
                buffer[row][col] = '#';
            } else {
                buffer[row][col] = '.';
            }
        }
        buffer[row][12] = '\0';
        rows[row] = buffer[row];
    }
}

