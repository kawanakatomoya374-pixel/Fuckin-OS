/* Keep HTTP/1.1 explicit during the transition. Advertising h2 before a
 * frame/HPACK implementation is attached would make successful TLS handshakes
 * unusable because the HTTP/1 request line is invalid on an h2 connection. */
static const char *tls_alpn_http1[] = { "http/1.1" };
static const char *tls_alpn_http2[] = { "h2", "http/1.1" };

struct tls_session {
    socket_t* socket;
    br_ssl_client_context client;
    br_x509_minimal_context x509;
    br_sslio_context ioc;
    unsigned char iobuf[BR_SSL_BUFSIZE_BIDI];
    /* Per-session cadence. A global poll counter coupled independent TLS
     * handshakes and becomes a data race as soon as multiple transports run. */
    uint32_t poll_since_yield;
};

/* BearSSL deliberately starts with no PRNG state.  Seed it from the x86
 * hardware RNG when available; retain a bounded timing-jitter fallback so
 * TLS can still initialise on older virtual CPUs. */
static int tls_cpu_has_rdrand(void) {
    uint32_t eax, ebx, ecx, edx;
    __asm__ volatile("cpuid" : "=a"(eax), "=b"(ebx), "=c"(ecx), "=d"(edx)
                     : "a"(1), "c"(0));
    return (ecx & (1u << 30)) != 0;
}

static uint64_t tls_rdtsc(void) {
    uint32_t lo, hi;
    __asm__ volatile("rdtsc" : "=a"(lo), "=d"(hi));
    return ((uint64_t)hi << 32) | lo;
}

static int tls_is_leap_year(uint64_t year) {
    return (year % 4u == 0u) && ((year % 100u != 0u) || (year % 400u == 0u));
}

static uint32_t tls_days_since_year_zero(uint64_t year, uint8_t month, uint8_t day) {
    static const uint8_t month_days[] = { 31, 28, 31, 30, 31, 30,
                                           31, 31, 30, 31, 30, 31 };
    /* Days before January 1 of `year`, with astronomical year zero
     * included as BearSSL specifies. */
    uint64_t days = year * 365u + (year + 3u) / 4u
                    - (year + 99u) / 100u + (year + 399u) / 400u;
    for (uint8_t m = 1; m < month && m <= 12; ++m) days += month_days[m - 1];
    if (month > 2 && tls_is_leap_year(year)) ++days;
    if (day > 0) days += (uint64_t)day - 1u;
    return (uint32_t)days;
}

static void tls_seed_entropy(br_ssl_engine_context* engine) {
    unsigned char seed[32];
    int has_rdrand = tls_cpu_has_rdrand();
    for (size_t i = 0; i < sizeof(seed); i += sizeof(uint64_t)) {
        uint64_t word = 0;
        unsigned char ok = 0;
        if (has_rdrand) {
            __asm__ volatile("rdrand %0; setc %1" : "=r"(word), "=qm"(ok));
        }
        if (!ok) {
            /* Mix timestamp counter, PIT time, address variation and a
             * short software jitter loop.  RDRAND remains the normal path. */
            word = tls_rdtsc() ^ (get_timer_ticks() << 17) ^ (uint64_t)(uintptr_t)&seed[i];
            for (unsigned int j = 0; j < 64; ++j) {
                word ^= tls_rdtsc() + ((uint64_t)j << (j & 15));
            }
        }
        for (size_t b = 0; b < sizeof(word); ++b) {
            seed[i + b] = (unsigned char)(word >> (b * 8));
        }
    }
    br_ssl_engine_inject_entropy(engine, seed, sizeof(seed));
}

/* socket_send()/socket_recv() are non-blocking from the TLS layer's point
 * of view: a zero result means the NIC must be serviced before the TCP
 * connection can make progress.  BearSSL's blocking callbacks must drive
 * that progress rather than treating a temporary would-block as a fatal
 * transport error. */
#define TLS_IO_TIMEOUT_MS 10000u

static void tls_drive_network(tls_session_t *session) {
    if (session == NULL) return;
    net_poll();
    /* Yielding after every would-block turned a short TLS handshake into about
     * five seconds of scheduler round-trips. Keep this cadence per session so
     * one congested transfer cannot alter the scheduling of another TLS state
     * machine once concurrent transport workers are enabled. */
    if (++session->poll_since_yield >= 64u) {
        session->poll_since_yield = 0;
        thread_yield();
    }
}

static int tls_low_read(void* ctx, unsigned char* data, size_t len) {
    tls_session_t* session = (tls_session_t*)ctx;
    if (!session || !session->socket || !data || len == 0) return -1;

    uint64_t deadline = get_timer_ticks() + TLS_IO_TIMEOUT_MS;
    while (get_timer_ticks() < deadline) {
        int r = socket_recv(session->socket, data, len, 0);
        if (r > 0) return r;
        if (r < 0) {
            serial_puts("[TLS] Low-level receive failed\n");
            return -1;
        }
        tls_drive_network(session);
    }
    uint64_t dispatch_passes = 0;
    uint64_t dispatch_contended = 0;
    net_get_dispatch_stats(&dispatch_passes, &dispatch_contended);
    serial_puts("[TLS] Receive timed out; net passes=");
    serial_putdec(dispatch_passes);
    serial_puts(" contended=");
    serial_putdec(dispatch_contended);
    serial_puts("\n");
    return -1;
}

static int tls_low_write(void* ctx, const unsigned char* data, size_t len) {
    tls_session_t* session = (tls_session_t*)ctx;
    if (!session || !session->socket || !data || len == 0) return -1;

    size_t sent = 0;
    uint64_t deadline = get_timer_ticks() + TLS_IO_TIMEOUT_MS;
    while (sent < len && get_timer_ticks() < deadline) {
        int r = socket_send(session->socket, (void*)(data + sent), len - sent, 0);
        if (r < 0) {
            serial_puts("[TLS] Low-level send failed\n");
            return -1;
        }
        if (r == 0) {
            tls_drive_network(session);
            continue;
        }
        sent += (size_t)r;
        deadline = get_timer_ticks() + TLS_IO_TIMEOUT_MS;
    }
    if (sent != len) {
        serial_puts("[TLS] Send timed out\n");
        return -1;
    }
    return (int)sent;
}

static void tls_session_destroy(tls_session_t* session) {
    if (!session) {
        return;
    }
    if (session->socket) {
        socket_close(session->socket);
        session->socket = NULL;
    }
    kfree(session);
}

int tls_backend_available(void) {
    return 1;
}

static tls_session_t* tls_connect_with_alpn(const char* host, uint64_t port,
                                            const char **protocols,
                                            size_t protocol_count) {
    if (!host || !host[0]) {
        return NULL;
    }

    ip_addr_t server_ip;
    int resolved = dns_resolve(host, &server_ip);
    if (resolved < 0) {
        serial_puts("[TLS] Resolving host: ");
        serial_puts(host);
        serial_puts("...\n");
        /* DHCP/usernet DNS is asynchronous: four immediate polls can expire
         * before the first UDP reply is processed, causing the GUI's first
         * clicked HTTPS page to show a false transport error while its later
         * favicon request succeeds. Wait for a bounded real-time window and
         * keep servicing the NIC/scheduler until the cache is populated. */
        uint64_t dns_deadline = get_timer_ticks() + 3000u;
        while (resolved < 0 && get_timer_ticks() < dns_deadline) {
            net_poll();
            thread_yield();
            resolved = dns_resolve(host, &server_ip);
        }
        if (resolved < 0) {
            serial_puts("[TLS] DNS resolution failed for ");
            serial_puts(host);
            serial_puts("\n");
            return NULL;
        }
    }

    tls_session_t* session = (tls_session_t*)kmalloc(sizeof(tls_session_t));
    if (!session) {
        serial_puts("[TLS] Out of memory\n");
        return NULL;
    }
    memset(session, 0, sizeof(*session));

    session->socket = socket_create(AF_INET, SOCK_STREAM, 0);
    if (!session->socket) {
        serial_puts("[TLS] Failed to create socket\n");
        tls_session_destroy(session);
        return NULL;
    }

    sock_addr_t addr;
    addr.family = AF_INET;
    addr.port = (uint16_t)port;
    addr.addr = server_ip;

    if (socket_connect(session->socket, &addr) < 0) {
        serial_puts("[TLS] Socket connect failed\n");
        tls_session_destroy(session);
        return NULL;
    }

    br_ssl_client_init_full(&session->client, &session->x509,
        COS_SYSTEM_TRUST_ANCHORS, COS_SYSTEM_TRUST_ANCHORS_COUNT);
    rtc_time_t now = rtc_get_datetime();
    if (now.year >= 2000u && now.month >= 1u && now.month <= 12u &&
        now.day >= 1u && now.day <= 31u && now.hour < 24u &&
        now.minute < 60u && now.second < 60u) {
        br_x509_minimal_set_time(&session->x509,
            tls_days_since_year_zero(now.year, now.month, now.day),
            (uint32_t)now.hour * 3600u + (uint32_t)now.minute * 60u + now.second);
    } else {
        serial_puts("[TLS] RTC time unavailable for certificate validation\n");
    }
    tls_seed_entropy(&session->client.eng);
    br_ssl_engine_set_buffer(&session->client.eng, session->iobuf, sizeof(session->iobuf), 1);
    br_ssl_engine_set_protocol_names(&session->client.eng, protocols, protocol_count);
    br_ssl_client_reset(&session->client, host, 0);
    br_sslio_init(&session->ioc, &session->client.eng, tls_low_read, session, tls_low_write, session);
    /* Finish the handshake before returning. This makes ALPN authoritative to
     * the HTTP layer and prevents an h2 preface from ever being sent before
     * the peer's selected protocol is known. */
    if (br_sslio_flush(&session->ioc) < 0) {
        serial_puts("[TLS] Handshake failed error=");
        serial_putdec((uint64_t)br_ssl_engine_last_error(&session->client.eng));
        serial_puts("\n");
        tls_session_destroy(session);
        return NULL;
    }

    serial_puts("[TLS] Connected for ");
    serial_puts(host);
    const char* selected = br_ssl_engine_get_selected_protocol(&session->client.eng);
    if (selected != NULL) {
        serial_puts(" ALPN=");
        serial_puts(selected);
    }
    serial_puts("\n");
    return session;
}

tls_session_t* tls_connect(const char* host, uint64_t port) {
    return tls_connect_with_alpn(host, port, tls_alpn_http1, 1);
}

tls_session_t* tls_connect_prefer_http2(const char* host, uint64_t port) {
    return tls_connect_with_alpn(host, port, tls_alpn_http2, 2);
}

const char* tls_get_selected_protocol(tls_session_t* session) {
    if (session == NULL) return NULL;
    return br_ssl_engine_get_selected_protocol(&session->client.eng);
}

int tls_send(tls_session_t* session, const char* data, size_t len) {
    if (!session || !data || len == 0) {
        return -1;
    }
    uint64_t t_write_start = get_timer_ticks();
    if (br_sslio_write_all(&session->ioc, data, len) < 0) {
        serial_puts("[TLS] BearSSL write error=");
        serial_putdec((uint64_t)br_ssl_engine_last_error(&session->client.eng));
        serial_puts("\n");
        return -1;
    }
    uint64_t t_write_done = get_timer_ticks();
    if (br_sslio_flush(&session->ioc) < 0) {
        serial_puts("[TLS] BearSSL flush error=");
        serial_putdec((uint64_t)br_ssl_engine_last_error(&session->client.eng));
        serial_puts("\n");
        return -1;
    }
    uint64_t t_flush_done = get_timer_ticks();
    serial_puts("[TLS/PERF] write_all_ms=");
    serial_putdec(t_write_done - t_write_start);
    serial_puts(" flush_ms=");
    serial_putdec(t_flush_done - t_write_done);
    serial_puts(" total_ms=");
    serial_putdec(t_flush_done - t_write_start);
    serial_puts(" bytes=");
    serial_putdec((uint64_t)len);
    serial_puts("\n");
    return (int)len;
}

int tls_recv(tls_session_t* session, char* buffer, size_t max_len) {
    if (!session || !buffer || max_len == 0) {
        return -1;
    }
    return br_sslio_read(&session->ioc, buffer, max_len);
}

void tls_close(tls_session_t* session) {
    if (!session) return;
    /* HTTP uses Connection: close. Waiting synchronously for TLS close_notify
     * can block indefinitely on Internet peers after a successful response.
     * Releasing the transport is safe here and keeps NetSurf responsive. */
    tls_session_destroy(session);
}
