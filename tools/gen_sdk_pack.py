#!/usr/bin/env python3
"""Embed a directory tree (the on-device SDK) as C data: a table of {path, data, len}.

Used to ship /system/sdk/include and /system/sdk/lib inside the kernel image; the boot-time
layout code (cos_system_layout.c) writes each entry to disk when it is missing or its size
differs. Paths are stored relative to the root given with --root and are emitted in sorted
order so the output is reproducible."""
import argparse, os, sys

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--root', required=True)
    p.add_argument('--out', required=True)
    p.add_argument('--name', default='sdk', help='symbol prefix: cos_<name>_files, COS_<NAME>_FILE_COUNT')
    p.add_argument('--exclude', action='append', default=[], help='top-level directories of --root to leave out')
    p.add_argument('--overlay', action='append', default=[], help='directory whose files are added over the tree (same relative paths replace)')
    a = p.parse_args()
    table = {}
    for root in [a.root] + a.overlay:
        for d, dirs, names in os.walk(root):
            if root == a.root and os.path.relpath(d, root) == '.':
                dirs[:] = [x for x in dirs if x not in a.exclude]
            for n in names:
                full = os.path.join(d, n)
                table[os.path.relpath(full, root).replace(os.sep, '/')] = full
    files = sorted(table.items())
    N, U = a.name, a.name.upper()
    out = ['/* Generated by tools/gen_sdk_pack.py - do not edit. */\n',
           '#ifndef COS_%s_PACK_H\n#define COS_%s_PACK_H\n' % (U, U)]
    total = 0
    for i, (rel, full) in enumerate(files):
        data = open(full, 'rb').read()
        total += len(data)
        out.append('static const unsigned char cos_%s_f%d[] = {\n' % (N, i))
        for k in range(0, len(data), 16):
            out.append('    ' + ''.join('0x%02x,' % b for b in data[k:k+16]) + '\n')
        if not data:
            out.append('    0\n')
        out.append('};\n')
    out.append('#ifndef COS_SDK_FILE_T\n#define COS_SDK_FILE_T\ntypedef struct { const char *path; const unsigned char *data; unsigned int len; } cos_sdk_file_t;\n#endif\n')
    out.append('static const cos_sdk_file_t cos_%s_files[] = {\n' % N)
    for i, (rel, full) in enumerate(files):
        out.append('    { "%s", cos_%s_f%d, %du },\n' % (rel, N, i, os.path.getsize(full)))
    out.append('};\n#define COS_%s_FILE_COUNT %d\n#endif\n' % (U, len(files)))
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, 'w').writelines(out)
    print('sdk pack: %d files, %d bytes -> %s' % (len(files), total, a.out))

if __name__ == '__main__':
    sys.exit(main())
