#!/usr/bin/env python3
"""gen_kernel_update_keys.py [BUILD_DIR] [--public FILE] - the key that signs KERNEL updates (docs/app_update.md, stage 2).

It is a different key from the one that signs app updates (gen_update_keys.py): a kernel is the most powerful thing that can be delivered, so its key is kept apart and the
kernel itself (src/kernel/cos_bootupd.c) checks the signature, not a program. By default a development key is made in BUILD_DIR/update/kernel_update_key.pem;
a release names the PUBLIC half of its own key (make KERNEL_PUBKEY=release/kernel_update_public.pem). BUILD_DIR/kernel_pubkey.h is what the kernel is compiled with."""
import os, sys
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives import serialization
args = sys.argv[1:]
public = None
if "--public" in args:
    i = args.index("--public"); public = args[i + 1]; del args[i:i + 2]
out = args[0] if args else "build"
d = os.path.join(out, "update"); os.makedirs(d, exist_ok=True)
kp = os.path.join(d, "kernel_update_key.pem")
if public:
    data = open(public, "rb").read()
    try: pubkey = serialization.load_pem_public_key(data)
    except ValueError: pubkey = serialization.load_pem_private_key(data, None).public_key()
else:
    if os.path.exists(kp): key = serialization.load_pem_private_key(open(kp, "rb").read(), None)
    else:
        key = ec.generate_private_key(ec.SECP256R1())
        fd = os.open(kp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "wb") as f: f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    pubkey = key.public_key()
pub = pubkey.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
body = "/* generated by tools/gen_kernel_update_keys.py: the public key the kernel verifies kernel updates with (uncompressed P-256 point) */\nstatic const unsigned char cos_kupd_pubkey[65] = {%s};\n" % ",".join("0x%02x" % b for b in pub)
hp = os.path.join(out, "kernel_pubkey.h")
if not os.path.exists(hp) or open(hp).read() != body: open(hp, "w").write(body)
