#!/usr/bin/env python3
"""Pack a mc-classic-c resource directory into a C file: the game's files (the sound files excluded unless --sounds) become one
blob the C-OS port unpacks into its working directory on first start.  usage: mc_pack.py RESDIR GAMEDIR OUT.c [--sounds]"""
import os, struct, sys

def main():
    res, gamedir, out = sys.argv[1:4]
    sounds = "--sounds" in sys.argv
    blob = bytearray(b"MCP1")
    for root, _, files in sorted(os.walk(res)):
        for name in sorted(files):
            full = os.path.join(root, name)
            rel = os.path.relpath(full, os.path.dirname(res.rstrip("/")))      # resources/terrain.png
            if not sounds and rel.endswith((".ogg", ".wav")): continue
            data = open(full, "rb").read()
            path = (gamedir.rstrip("/") + "/" + rel).encode()
            blob += struct.pack("<HI", len(path), len(data)) + path + data
    lines = ["/* generated by tools/mc_pack.py */", "const unsigned char mc_pack[] = {"]
    for i in range(0, len(blob), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in blob[i:i + 16]) + ",")
    lines += ["};", "const unsigned int mc_pack_len = %dU;" % len(blob), 'const char mc_game_dir[] = "%s";' % gamedir.rstrip("/"), ""]
    open(out, "w").write("\n".join(lines))

main()
