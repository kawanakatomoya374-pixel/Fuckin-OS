#!/usr/bin/env python3
"""linux_rootfs_pack.py OUT.h OUT.inc HOST:GUEST [HOST:GUEST ...] - files for the root file system of Linux programs (docs/LINUX_COMPAT.md), as C arrays
(OUT.h) and the installer lines for cos_system_layout.c (OUT.inc). GUEST is the C-OS path, normally below /linux. Used by the VALIDATION_TESTPROGS build with
LINUX_ROOTFS="host:guest ..." (for experiments with real Linux programs: nothing here is part of a normal build)."""
import os, sys
out_h, out_inc, specs = sys.argv[1], sys.argv[2], sys.argv[3:]
if len(specs) == 1 and specs[0].startswith("@"): specs = open(specs[0][1:]).read().split()      # @file: the entries, whitespace separated
h = ["/* generated by tools/linux_rootfs_pack.py */"]; inc = ["/* generated by tools/linux_rootfs_pack.py */"]
dirs = set()
for n, spec in enumerate(specs):
    host, guest = spec.split(":", 1)
    data = open(host, "rb").read()
    sym = "cos_lxroot_%d" % n
    h.append("static const unsigned char %s[] = {" % sym)
    for i in range(0, len(data), 24): h.append("    " + ",".join("0x%02X" % b for b in data[i:i + 24]) + ",")
    h.append("};")
    parts = [p for p in guest.split("/") if p]
    cur = ""
    for p in parts[:-1]:
        if cur + "/" + p not in dirs:
            dirs.add(cur + "/" + p); inc.append('    ensure_dir("%s", "%s");' % (cur or "/", p))
        cur += "/" + p
    inc.append('    ensure_file("%s", "%s", %s, sizeof %s);' % (cur or "/", parts[-1], sym, sym))
open(out_h, "w").write("\n".join(h) + "\n"); open(out_inc, "w").write("\n".join(inc) + "\n")
