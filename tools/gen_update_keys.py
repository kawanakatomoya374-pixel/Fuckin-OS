#!/usr/bin/env python3
"""gen_update_keys.py [BUILD_DIR] [--public RELEASE_PUBLIC_KEY.pem] - the key that signs app-update manifests (docs/app_update.md).

An ECDSA P-256 key is created once in BUILD_DIR/update/update_key.pem (a development key; a release keeps the private key off the build machine and signs
the manifests elsewhere). BUILD_DIR/update/update_pubkey.h holds the PUBLIC key as a C array for cosupdate, the program that checks manifests."""
import os, sys
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives import serialization
args = [a for a in sys.argv[1:]]
public = None
if "--public" in args:                                         # a release: the public key of a key that lives elsewhere (make UPDATE_PUBKEY=release_public.pem)
    i = args.index("--public"); public = args[i + 1]; del args[i:i + 2]
out = args[0] if args else "build"
d = os.path.join(out, "update"); os.makedirs(d, exist_ok=True)
kp = os.path.join(d, "update_key.pem")
if public:
    data = open(public, "rb").read()
    try: pubkey = serialization.load_pem_public_key(data)
    except ValueError: pubkey = serialization.load_pem_private_key(data, None).public_key()      # a private key file is accepted: only its public half is used
    key = None
elif os.path.exists(kp): key = serialization.load_pem_private_key(open(kp, "rb").read(), None)
else:
    key = ec.generate_private_key(ec.SECP256R1())
    fd = os.open(kp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f: f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
if key is not None: pubkey = key.public_key()
pub = pubkey.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
body = "/* generated by tools/gen_update_keys.py: the public key cosupdate verifies update manifests with (uncompressed P-256 point) */\nstatic const unsigned char cos_update_pubkey[65] = {%s};\n" % ",".join("0x%02x" % b for b in pub)
hp = os.path.join(d, "update_pubkey.h")
if not os.path.exists(hp) or open(hp).read() != body: open(hp, "w").write(body)
