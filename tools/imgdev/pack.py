#!/usr/bin/env python3
"""Pack the files of a directory (gen.py output) into a C header: cos_imgdev_files[] = {name, data, len}, for the validation kernel image."""
import json, os, sys
src, dst = sys.argv[1], sys.argv[2]
names = list(json.load(open(os.path.join(src, 'manifest.json'))).keys())
files = [(n, open(os.path.join(src, n), 'rb').read()) for n in names if os.path.exists(os.path.join(src, n))]
files.append(('names.txt', ('\n'.join(names) + '\n').encode()))
out = ['/* Generated by tools/imgdev/pack.py - do not edit. */\n#ifndef COS_IMGDEV_FILES_H\n#define COS_IMGDEV_FILES_H\n']
for i, (n, d) in enumerate(files):
    out.append('static const unsigned char imgdev_f%d[] = {\n' % i)
    for k in range(0, len(d), 16): out.append('    ' + ','.join('0x%02x' % b for b in d[k:k + 16]) + ',\n')
    if not d: out.append('    0\n')
    out.append('};\n')
out.append('static const struct { const char *name; const unsigned char *data; unsigned len; } cos_imgdev_files[] = {\n')
for i, (n, d) in enumerate(files): out.append('    { "%s", imgdev_f%d, %du },\n' % (n, i, len(d)))
out.append('    { 0, 0, 0 }\n};\n#endif\n')
open(dst, 'w').write(''.join(out))
