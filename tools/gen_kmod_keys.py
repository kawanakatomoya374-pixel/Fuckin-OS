#!/usr/bin/env python3
"""gen_kmod_keys.py [BUILD_DIR [TRUSTED_LEVEL]] - the module signing keys of this build tree.

There is one ECDSA P-256 key per permission level a module may declare (see src/include/cosys.h): the key of level N may sign modules that declare level N or
less (key 1: BASIC and SERVICE, key 2: + DEVICE, key 3: + SYSTEM). The private keys are created once in BUILD_DIR/kmod/kmod_key_l<N>.pem (development keys;
a release keeps them off the build machine - in particular key 3, whose signature lets a module read and change every program's data).
The kernel header BUILD_DIR/kmod_pubkey.h lists the PUBLIC keys of the levels 1..TRUSTED_LEVEL (default 3): a kernel built with TRUSTED_LEVEL 2 does not know key 3
at all, so no SYSTEM-level module can ever be loaded into it, whoever signed it."""
import os, sys
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives import serialization
out = sys.argv[1] if len(sys.argv) > 1 else "build"
trusted = int(sys.argv[2]) if len(sys.argv) > 2 else 3
if not 1 <= trusted <= 3: sys.exit("TRUSTED_LEVEL must be 1, 2 or 3")
kdir = os.path.join(out, "kmod"); os.makedirs(kdir, exist_ok=True)
entries = []
for level in (1, 2, 3):
    kp = os.path.join(kdir, "kmod_key_l%d.pem" % level)
    if os.path.exists(kp): key = serialization.load_pem_private_key(open(kp, "rb").read(), None)
    else:
        key = ec.generate_private_key(ec.SECP256R1())
        fd = os.open(kp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "wb") as f: f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    if level <= trusted:
        pub = key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
        entries.append("    { %d, {%s} }," % (level, ",".join("0x%02x" % b for b in pub)))
body = ("/* generated by tools/gen_kmod_keys.py: the public keys the kernel verifies .c-osys signatures with (key id = the highest module level the key may sign) */\n"
        "#define COS_KMOD_TRUSTED_LEVEL %d\n"
        "static const struct { unsigned level; unsigned char pub[65]; } cos_kmod_keys[] = {\n%s\n};\n") % (trusted, "\n".join(entries))
hp = os.path.join(out, "kmod_pubkey.h")
if not os.path.exists(hp) or open(hp).read() != body: open(hp, "w").write(body)
