#!/usr/bin/env python3
"""mc_audio_pack.py AUDIODIR OUT.h OUT.inc - the sound and music files of mc-classic-c, shared by every version (they are identical),
as C arrays (OUT.h) and the installer lines for cos_system_layout.c (OUT.inc): /apps/minecraft/audio/<relative path>."""
import os, sys
src, out_h, out_inc = sys.argv[1:4]
h = ["/* generated by tools/mc_audio_pack.py */"]; inc = ["/* generated by tools/mc_audio_pack.py */", '    ensure_dir("/apps/minecraft", "audio");']
dirs = set(); n = 0
for root, _, files in sorted(os.walk(src)):
    for name in sorted(files):
        full = os.path.join(root, name); rel = os.path.relpath(full, src)
        sym = "cos_mcaudio_%d" % n; n += 1
        data = open(full, "rb").read()
        h.append("static const unsigned char %s[] = {" % sym)
        for i in range(0, len(data), 24): h.append("    " + ",".join("0x%02X" % b for b in data[i:i + 24]) + ",")
        h.append("};")
        parts = rel.split(os.sep); cur = "/apps/minecraft/audio"
        for p in parts[:-1]:
            if cur + "/" + p not in dirs: dirs.add(cur + "/" + p); inc.append('    ensure_dir("%s", "%s");' % (cur, p))
            cur += "/" + p
        inc.append('    ensure_file("%s", "%s", %s, sizeof %s);' % (cur, parts[-1], sym, sym))
open(out_h, "w").write("\n".join(h) + "\n"); open(out_inc, "w").write("\n".join(inc) + "\n")
