/* header.c - plugin of Py2C Studio: puts a comment with the source file and the date on top of every generated C file (output filter). The text after
 * "Author:" comes from the plugin's setting "author" (/system/plugins/config/p2c-header.cfg), which Settings > Extensions can edit. */
#include "cos_plugin.h"
#include "cos_plugin_py2c.h"
#include "cos_plugin_util.h"
static const py2c_api_t *A;
static int out_filter(char *c, size_t cap) {
    if (!pu_ncmp(c, "/* Generated by Py2C Studio", 27)) return 0;
    int y = 2025, mo = 1, d = 1, h = 0, mi = 0, s = 0; A->base.datetime(&y, &mo, &d, &h, &mi, &s);
    char who[48] = ""; A->base.cfg_get("p2c-header", "author", who, sizeof who);
    char head[300]; A->base.snprintf(head, sizeof head, "/* Generated by Py2C Studio from %s on %04d-%02d-%02d %02d:%02d%s%s */\n", A->path()[0] ? A->path() : "untitled.py", y, mo, d, h, mi, who[0] ? "  Author: " : "", who);
    size_t hl = pu_len(head), cl = pu_len(c);
    if (cl + hl + 1 > cap) return 0;
    for (size_t i = cl + 1; i-- > 0; ) c[i + hl] = c[i];
    pu_cpy(c, head, hl); A->base.log("[P2C-HEADER] header added\n"); return 1;
}
static int init(const cos_plugin_host_t *h) {
    A = (const py2c_api_t *)h->api;
    if (!A || A->abi != PY2CP_ABI) return -1;
    return A->add_output_filter(out_filter);
}
static void fini(void) { A = 0; }
COS_PLUGIN("py2c", "header", "1.0", init, fini);
