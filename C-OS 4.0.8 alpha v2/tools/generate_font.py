def generate_simple_char(codepoint):
    """Generate a simple 12x16 bitmap for any ASCII character"""
    if codepoint == 0x20:  # Space
        return ["............"] * 16
    
    # For other characters, create a simple pattern based on the codepoint
    # This ensures all characters have some representation
    rows = []
    for row in range(16):
        line = list("............")
        # Create a simple pattern based on codepoint
        for col in range(12):
            if (codepoint + row + col) % 7 == 0:
                line[col] = '#'
        rows.append(''.join(line))
    return rows

def generate_font_data():
    """Generate font data in C format"""
    output = []
    output.append('#include "vga_font24.h"')
    output.append('#include "font24x24.h"')
    output.append('')
    output.append('/*')
    output.append(' * Simple 12x16 font generated for C-OS')
    output.append(' * ASCII printable characters (0x20-0x7E)')
    output.append(' */')
    output.append('')
    output.append('const vga_font24_glyph_t font24x24[] = {')
    
    # Generate characters from 0x20 to 0x7E
    for codepoint in range(0x20, 0x7F):
        if codepoint in font_bitmaps:
            rows = char_to_bits(font_bitmaps[codepoint])
        else:
            # Generate a simple pattern for undefined characters
            rows = char_to_bits(generate_simple_char(codepoint))
        
        row_str = ','.join(rows)
        output.append(f'    {{0x{codepoint:04x}u, {{{row_str}}}}},')
    
    output.append('};')
    return '\n'.join(output)

if __name__ == '__main__':
    font_data = generate_font_data()
    # Write directly to file to avoid encoding issues
    output_file = 'src/drivers/video/font24x24_data.c'
    with open(output_file, 'w', encoding='utf-8') as f:
        f.write(font_data)
    print(f"Font data written to {output_file}")
