"""
Simple 12x16 font generator for C-OS
Generates font data compatible with the rendering logic:
- bit_idx = 11 - col (extracts bits from right to left)
- glyph->rows[row] (rows are not reversed)
"""

# Simple 12x16 bitmap font data for ASCII 0x20-0x7E
# Each character is 16 rows of 12 pixels
# Bits are stored with bit 11 = leftmost pixel, bit 0 = rightmost pixel

def char_to_bits(char_data):
    """Convert character bitmap to uint32_t values"""
    rows = []
    for row in char_data:
        # Convert 12-bit row to uint32_t
        # row is a string of 12 characters ('.' for empty, '#' for pixel)
        bits = 0
        for i, pixel in enumerate(row):
            if pixel == '#':
                bits |= (1 << (11 - i))  # bit 11 is leftmost, bit 0 is rightmost
        rows.append(f"0x{bits:04x}u")
    return rows

